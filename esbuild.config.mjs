import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";
import { copyFileSync, mkdirSync, readFileSync } from "fs";
import { exec } from "child_process";
import path from "path";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === "production";

// Dev in a real vault: FRAGMENT_VAULT="<vault folder>" npm run dev
// After each rebuild, main.js / manifest.json / styles.css are copied into
// <vault>/.fragment/plugins/<id>/ and the running Fragment reloads the plugin.
const vault = process.env.FRAGMENT_VAULT;
const readManifest = () => readFileSync("manifest.json", "utf8");
const devVault = {
	name: "dev-vault",
	setup(build) {
		build.onEnd((result) => {
			if (!vault || result.errors.length) return;
			const id = JSON.parse(readManifest()).id;
			const dir = path.join(vault, ".fragment", "plugins", id);
			mkdirSync(dir, { recursive: true });
			for (const f of ["main.js", "manifest.json", "styles.css"]) copyFileSync(f, path.join(dir, f));
			exec(`fragment plugin-reload id=${id} vault="${path.basename(vault)}"`, (err, out, errOut) => {
				console.log(err ? `[dev-vault] reload failed: ${errOut || err.message}` : `[dev-vault] ${id} reloaded in ${path.basename(vault)}`);
			});
		});
	},
};

const context = await esbuild.context({
	banner: { js: banner },
	entryPoints: ["src/main.ts"],
	bundle: true,
	// The host injects these at runtime via a require shim, so they must NOT be
	// bundled. `fragment` is the module a plugin imports; `obsidian` is an alias.
	external: [
		"fragment",
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtins,
	],
	format: "cjs",
	target: "es2022",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
	minify: prod,
	plugins: [devVault],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
